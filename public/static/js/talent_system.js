    // Отрисовка всех порогов ветки
    function renderThresholds(branch, characterClass) {
        const pointsInBranch = talentPoints[characterClass][branch.name];
        const selectedInBranch = selectedTalents[characterClass][branch.name] || {};

        return branch.thresholds.map(threshold => {
            const isUnlocked = pointsInBranch >= threshold.pointsRequired;
            const selectedId = selectedInBranch[threshold.pointsRequired];

            return `
                <div class="talent-threshold ${isUnlocked ? 'unlocked' : 'locked'}"
                    data-points="${threshold.pointsRequired}">
                    <div class="talent-threshold-header">
                        <span class="threshold-badge">${threshold.pointsRequired}</span>
                        <span class="threshold-text">
                            ${isUnlocked
                                ? (selectedId ? '✅ Выбрано' : 'Выберите умение (или пропустите)')
                                : `🔒 Требуется ${threshold.pointsRequired} очков в ветке`}
                        </span>
                    </div>
                    <div class="talent-options">
                        ${threshold.talents.map(talent => {
                            const isSelected = selectedId === talent.id;
                            const isBlockedByOther = selectedId && !isSelected;
                            const canSelect = isUnlocked && !selectedId && spentPoints < MAX_TOTAL_POINTS;
                            const canDeselect = isSelected;

                            // Экранируем описание для data-атрибута
                            const safeName = String(talent.name).replace(/"/g, '&quot;');
                            const safeDesc = String(talent.description || '')
                                .replace(/"/g, '&quot;')
                                .replace(/</g, '&lt;')
                                .replace(/>/g, '&gt;');

                            return `
                                <div class="talent-item ${isSelected ? 'selected unlocked' : (isUnlocked ? 'unlocked' : 'locked')} ${isBlockedByOther ? 'blocked' : ''}"
                                    data-branch="${branch.name}"
                                    data-threshold="${threshold.pointsRequired}"
                                    data-talent-id="${talent.id}"
                                    data-talent-name="${safeName}"
                                    data-talent-desc="${safeDesc}">
                                    <div class="talent-points-required">${threshold.pointsRequired}</div>
                                    <div class="talent-info">
                                        <h4>${talent.name}</h4>
                                    </div>
                                    <div class="talent-actions">
                                        ${isSelected ? `
                                            <button class="talent-select-btn deselect-btn"
                                                    data-branch="${branch.name}"
                                                    data-threshold="${threshold.pointsRequired}"
                                                    data-talent-id="${talent.id}"
                                                    ${!canDeselect ? 'disabled' : ''}>
                                                Снять
                                            </button>
                                        ` : (isUnlocked ? `
                                            <button class="talent-select-btn select-btn"
                                                    data-branch="${branch.name}"
                                                    data-threshold="${threshold.pointsRequired}"
                                                    data-talent-id="${talent.id}"
                                                    ${!canSelect ? 'disabled' : ''}>
                                                Выбрать
                                            </button>
                                        ` : `
                                            <div class="talent-lock">🔒</div>
                                        `)}
                                    </div>
                                    <div class="talent-status">
                                        ${isSelected ? '✓' : (isUnlocked ? '⚡' : '✗')}
                                    </div>
                                </div>
                            `;
                        }).join('')}
                    </div>
                </div>
            `;
        }).join('');
    }

