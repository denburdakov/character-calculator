    function getBranchInfo(branch, points, selected) {
        let html = '<div class="branch-info-content">';

        const nextThreshold = THRESHOLDS.find(t => t > points);
        if (nextThreshold) {
            html += `<div class="branch-info-next">⚡ До следующего порога: <strong>${nextThreshold - points}</strong> очк. (порог ${nextThreshold})</div>`;
        } else {
            html += '<div class="branch-info-complete">✅ Все пороги ветки открыты!</div>';
        }

        const selectedList = Object.entries(selected || {})
            .map(([threshold, id]) => {
                const th = branch.thresholds.find(t => t.pointsRequired === parseInt(threshold, 10));
                const talent = th?.talents.find(t => t.id === id);
                return talent ? `${talent.name} (порог ${threshold})` : null;
            })
            .filter(Boolean);

        if (selectedList.length > 0) {
            html += '<div class="branch-info-selected">📋 Выбраны:<ul>';
            selectedList.forEach(name => { html += `<li>${name}</li>`; });
            html += '</ul></div>';
        }

        html += '</div>';
        return html;
    }

    // ============================================================
    // ДЕЙСТВИЯ
    // ============================================================
    function addPointToBranch(branchName) {
        if (spentPoints >= MAX_TOTAL_POINTS) {
            alert(`❌ Достигнут максимум очков талантов (${MAX_TOTAL_POINTS})`);
            return;
        }
        if (availablePoints <= 0) return;
        if (talentPoints[currentClass][branchName] >= MAX_PER_BRANCH) return;

        talentPoints[currentClass][branchName]++;
        availablePoints--;
        spentPoints++;

        window.talentSystemData.availablePoints = availablePoints;
        window.talentSystemData.spentPoints = spentPoints;
        window.talentSystemData.talentPoints = talentPoints;

        loadTalentsForClass(currentClass);
        applyTalents();
    }

    function selectTalent(branchName, threshold, talentId) {
        if (spentPoints >= MAX_TOTAL_POINTS) {
            alert(`❌ Достигнут максимум очков талантов (${MAX_TOTAL_POINTS}).`);
            return;
        }
        if (talentPoints[currentClass][branchName] < threshold) {
            alert(`❌ Нужно ${threshold} очков в ветке, чтобы выбрать это умение.`);
            return;
        }

        if (!selectedTalents[currentClass][branchName]) {
            selectedTalents[currentClass][branchName] = {};
        }

        // Если уже выбран другой талант на этом пороге — сначала снимаем
        if (selectedTalents[currentClass][branchName][threshold]) {
            const oldId = selectedTalents[currentClass][branchName][threshold];
            if (oldId !== talentId) {
                alert('❌ На этом пороге уже выбран другой талант. Сначала снимите его.');
                return;
            }
        }

        selectedTalents[currentClass][branchName][threshold] = talentId;
        window.talentSystemData.selectedTalents = selectedTalents;

        loadTalentsForClass(currentClass);
        applyTalents();
    }

    function deselectTalent(branchName, threshold, talentId) {
        if (selectedTalents[currentClass][branchName] &&
            selectedTalents[currentClass][branchName][threshold] === talentId) {
            delete selectedTalents[currentClass][branchName][threshold];
            window.talentSystemData.selectedTalents = selectedTalents;
            loadTalentsForClass(currentClass);
            applyTalents();
        }
    }

    function updatePointsDisplay() {
        const counter = document.getElementById('points-counter');
        const avail = document.getElementById('available-points');
        const spent = document.getElementById('spent-points');
        if (counter) counter.textContent = `${spentPoints}/${MAX_TOTAL_POINTS}`;
        if (avail) avail.textContent = availablePoints;
        if (spent) spent.textContent = spentPoints;
    }

