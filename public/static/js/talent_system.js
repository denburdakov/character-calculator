    function bindEvents(characterClass) {
        // Вкладки
        document.querySelectorAll('.talents-tab-btn').forEach(btn => {
            btn.addEventListener('click', function() {
                const branchName = this.getAttribute('data-branch');
                currentActiveTab = branchName;
                document.querySelectorAll('.talents-tab-btn').forEach(b => b.classList.remove('active'));
                this.classList.add('active');
                document.querySelectorAll('.talents-tab-pane').forEach(p => p.classList.remove('active'));
                const pane = document.getElementById(`branch-${branchName}`);
                if (pane) pane.classList.add('active');
            });
        });

        // Кнопки "+"
        document.querySelectorAll('.add-point-btn').forEach(btn => {
            btn.addEventListener('click', function() {
                const branchName = this.getAttribute('data-branch');
                currentActiveTab = branchName;
                addPointToBranch(branchName);
            });
        });

        // Кнопки выбора/снятия
        document.querySelectorAll('.talent-select-btn').forEach(btn => {
            btn.addEventListener('click', function() {
                const branchName = this.getAttribute('data-branch');
                const threshold = parseInt(this.getAttribute('data-threshold'), 10);
                const talentId = this.getAttribute('data-talent-id');
                if (this.classList.contains('select-btn')) {
                    selectTalent(branchName, threshold, talentId);
                } else {
                    deselectTalent(branchName, threshold, talentId);
                }
            });
        });
        // Подключаем тултипы для талантов
        setupTalentTooltips();
    }

